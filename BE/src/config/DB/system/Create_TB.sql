USE ShopeeVipDB
GO
-- 1. Bảng Tài khoản
CREATE TABLE TAI_KHOAN (
    IDTaiKhoan INT IDENTITY(1,1) PRIMARY KEY,
    TenDangNhap VARCHAR(30) UNIQUE,
    Ten NVARCHAR(50),
    SDT VARCHAR(10),
    DiaChi NVARCHAR(MAX),
    Email VARCHAR(255),
    GioiTinh INT,
    MatKhau VARCHAR(100)
);

-- 2. Bảng Người Mua
CREATE TABLE NGUOI_MUA (
    IDNguoiMua INT IDENTITY(1,1) PRIMARY KEY ,
    IDTaiKhoan INT FOREIGN KEY REFERENCES TAI_KHOAN(IDTaiKhoan) UNIQUE,
    TrangThaiUser TINYINT
);

-- 3. Bảng Shop
CREATE TABLE SHOP (
    IDShop INT IDENTITY(1,1) PRIMARY KEY,
    IDTaiKhoan INT FOREIGN KEY REFERENCES TAI_KHOAN(IDTaiKhoan) UNIQUE,
    TrangThaiShop TINYINT
);


-- 4. Bảng Sản Phẩm
CREATE TABLE SAN_PHAM (
    IDSanPham INT IDENTITY(1,1) PRIMARY KEY,
    IDShop INT FOREIGN KEY REFERENCES SHOP(IDShop),
    TenSanPham NVARCHAR(50),
    MoTa NVARCHAR(MAX),
    HinhAnh VARCHAR(MAX),
    TrangThaiSP BIT
);

-- 5. Bảng Bản Sao Sản Phẩm (Biến thể)
CREATE TABLE BAN_SAO_SAN_PHAM (
    IDBanSao INT IDENTITY(1,1) PRIMARY KEY,
    IDSanPham INT FOREIGN KEY REFERENCES SAN_PHAM(IDSanPham),
    SoLuongTonKho INT,
    GiaBan DECIMAL(18,2),
    BienThe NVARCHAR(50), -- Ví dụ: Màu Đỏ, Size L
    HinhAnh VARCHAR(MAX),
    TrangThaiBS TINYINT DEFAULT 1
);

-- 6. Bảng Đơn Hàng
CREATE TABLE DON_HANG (
    IDDonHang INT IDENTITY(1,1) PRIMARY KEY,
    IDNguoiMua INT FOREIGN KEY REFERENCES NGUOI_MUA(IDNguoiMua),
    IDShop INT FOREIGN KEY REFERENCES SHOP(IDShop),
    NgayTao DATETIME,
    TrangThaiDonHang TINYINT DEFAULT 0
);

-- 7. Bảng Chi Tiết Đơn Hàng
CREATE TABLE CHI_TIET_DON_HANG (
    IDChiTiet INT IDENTITY(1,1) PRIMARY KEY,
    IDDonHang INT FOREIGN KEY REFERENCES DON_HANG(IDDonHang),
    IDBanSao INT FOREIGN KEY REFERENCES BAN_SAO_SAN_PHAM(IDBanSao),
    GiaLucMua DECIMAL(18,2),
    GhiChu NVARCHAR(MAX),
    SoLuong INT,
    GiaTien DECIMAL(18,2)
);

-- 8. Bảng Giỏ Hàng 
CREATE TABLE GIO_HANG (
    IDNguoiMua INT,
    IDBanSao INT,
    SoLuongMua INT,
    NgayThem DATETIME DEFAULT GETDATE(),
    PRIMARY KEY (IDNguoiMua, IDBanSao),
    FOREIGN KEY (IDNguoiMua) REFERENCES NGUOI_MUA(IDNguoiMua),
    FOREIGN KEY (IDBanSao) REFERENCES BAN_SAO_SAN_PHAM(IDBanSao)
);

CREATE TABLE VI(
    IDGiaoDich INT IDENTITY(1,1) PRIMARY KEY,
    IDShop INT FOREIGN KEY REFERENCES SHOP(IDShop),
    NoiDung NVARCHAR(255),
    SoTien DECIMAL(18,2),
    SoDu DECIMAL(18,2),
    NgayThucHien DATETIME DEFAULT GETDATE(),
    FOREIGN KEY(IDShop) REFERENCES SHOP(IDShop)
)
GO

CREATE TYPE TYPE_DanhSachMuaHang AS TABLE
(
    IDBanSao INT,
    SoLuongMua INT,
    ThanhTien DECIMAL(18,2)
);
GO

